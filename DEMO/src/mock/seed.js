export function makeLessonRecord(prefix, moduleIndex, lessonIndex, lesson) {
  return {
    id: `${prefix}-l${moduleIndex + 1}${lessonIndex + 1}`,
    title: lesson.title,
    duration: lesson.duration,
    type: lesson.type || "video",
    description:
      lesson.description ||
      `${lesson.title} builds practical skill through guided explanation, examples, and instructor notes.`,
    videoUrl: lesson.videoUrl || "https://www.youtube.com/watch?v=dQw4w9WgXcQ",
    content:
      lesson.content ||
      `Lesson summary for ${lesson.title}.\n\n- Explain the concept clearly\n- Show one practical example\n- Close with an action for the learner`,
    materials: lesson.materials || [
      { id: `${prefix}-mat-${moduleIndex + 1}${lessonIndex + 1}-1`, title: `${lesson.title} Slides`, type: "PDF", size: "1.2 MB" },
      { id: `${prefix}-mat-${moduleIndex + 1}${lessonIndex + 1}-2`, title: `${lesson.title} Workbook`, type: "DOC", size: "480 KB" },
    ],
    quiz: lesson.quiz || [
      {
        id: `${prefix}-lessonq-${moduleIndex + 1}${lessonIndex + 1}-1`,
        prompt: `What is the core takeaway from ${lesson.title}?`,
        options: ["A decorative detail", "A core practical concept", "An unrelated metric", "A disabled flow"],
        answer: 1,
        explanation: `This lesson is meant to teach a directly usable concept from ${lesson.title}.`,
      },
    ],
  };
}

function makeModules(prefix, specs) {
  return specs.map((spec, moduleIndex) => ({
    id: `${prefix}-m${moduleIndex + 1}`,
    title: spec.title,
    lessons: spec.lessons.map((lesson, lessonIndex) => makeLessonRecord(prefix, moduleIndex, lessonIndex, lesson)),
  }));
}

function makeQuiz(prefix, items) {
  return items.map((item, index) => ({
    id: `${prefix}-q${index + 1}`,
    prompt: item.prompt,
    options: item.options,
    answer: item.answer,
    explanation: item.explanation,
  }));
}

